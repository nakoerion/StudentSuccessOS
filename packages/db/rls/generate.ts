/**
 * RLS generator: ONE policy template applied to every tenant-scoped table.
 *
 *   pnpm rls:generate                 # rewrite the RLS migration in place
 *   pnpm rls:generate --check         # exit 1 if the migration is out of date
 *   pnpm rls:generate --name <dir>    # write a NEW migration dir (after adding tables)
 *
 * The output is idempotent (DROP POLICY IF EXISTS / CREATE POLICY), so a later
 * migration can simply re-emit the whole file after tables.ts grows.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import {
  APP_FUNCTIONS,
  APP_ROLE,
  GLOBAL_TABLES,
  type GlobalTable,
  TENANT_SCOPED_TABLES,
  type TenantScopedTable,
} from "./tables";

/**
 * Current tenant from the transaction-local setting. NULLIF guards against the
 * empty string Postgres returns once the setting has been used on a pooled
 * connection and then reset — an unset tenant must mean "no rows", not an error.
 */
export const CURRENT_TENANT_SQL = "NULLIF(current_setting('app.tenant_id', true), '')::uuid";

/** The latest generated RLS migration (earlier ones stay as history). */
export const DEFAULT_RLS_MIGRATION = "20261020000100_rls";

/** THE template. Every tenant-scoped table goes through this one function. */
export function policyFor({ table, scope }: TenantScopedTable): string {
  const match = `tenant_id = ${CURRENT_TENANT_SQL}`;
  const lines = [
    `-- ${table} (${scope})`,
    `ALTER TABLE "${table}" ENABLE ROW LEVEL SECURITY;`,
    `ALTER TABLE "${table}" FORCE ROW LEVEL SECURITY;`,
    `DROP POLICY IF EXISTS tenant_isolation ON "${table}";`,
    `CREATE POLICY tenant_isolation ON "${table}"`,
    `  USING (${match})`,
    `  WITH CHECK (${match});`,
    `DROP POLICY IF EXISTS shared_read ON "${table}";`,
  ];
  if (scope === "shared") {
    // Global rows (tenant_id IS NULL) are readable by every tenant. Writes still
    // go through tenant_isolation only, so the app can never modify them.
    lines.push(`CREATE POLICY shared_read ON "${table}" FOR SELECT USING (tenant_id IS NULL);`);
  }
  lines.push(`GRANT SELECT, INSERT, UPDATE, DELETE ON "${table}" TO ${APP_ROLE};`);
  return lines.join("\n");
}

/** Global tables: explicit privileges, optionally a self-row filter on the tenant id. */
export function globalTableSql({ table, privileges, selfColumn }: GlobalTable): string {
  const lines = [`REVOKE ALL ON "${table}" FROM ${APP_ROLE};`];
  if (privileges) lines.push(`GRANT ${privileges} ON "${table}" TO ${APP_ROLE};`);
  lines.push(`DROP POLICY IF EXISTS tenant_self ON "${table}";`);
  if (selfColumn) {
    lines.push(
      `ALTER TABLE "${table}" ENABLE ROW LEVEL SECURITY;`,
      `ALTER TABLE "${table}" FORCE ROW LEVEL SECURITY;`,
      `CREATE POLICY tenant_self ON "${table}" FOR SELECT USING (${selfColumn} = ${CURRENT_TENANT_SQL});`,
    );
  }
  return lines.join("\n");
}

export function renderRlsSql(): string {
  const header = [
    "-- GENERATED by packages/db/rls/generate.ts — do not edit by hand.",
    "-- Run `pnpm rls:generate` after changing rls/tables.ts.",
    "",
    `GRANT USAGE ON SCHEMA public TO ${APP_ROLE};`,
    "",
    "-- Global tables (no tenant_id): explicit, minimal privileges.",
    ...GLOBAL_TABLES.map(globalTableSql),
    `REVOKE ALL ON "_prisma_migrations" FROM ${APP_ROLE};`,
    "",
    "-- Pre-tenant lookups (SECURITY DEFINER, one key in, one subject out).",
    ...APP_FUNCTIONS.map((fn) => `GRANT EXECUTE ON FUNCTION ${fn} TO ${APP_ROLE};`),
    "",
    "-- Tenant-scoped tables: one template.",
  ];
  const body = TENANT_SCOPED_TABLES.map(policyFor);
  return [...header, body.join("\n\n"), ""].join("\n");
}

function migrationsDir(): string {
  return join(dirname(fileURLToPath(import.meta.url)), "..", "prisma", "migrations");
}

export function rlsMigrationPath(name = DEFAULT_RLS_MIGRATION): string {
  return join(migrationsDir(), name, "migration.sql");
}

function main(argv: string[]): void {
  const nameIdx = argv.indexOf("--name");
  const name = nameIdx >= 0 ? argv[nameIdx + 1] : DEFAULT_RLS_MIGRATION;
  if (!name) throw new Error("--name requires a migration directory name");
  const path = rlsMigrationPath(name);
  const sql = renderRlsSql();

  if (argv.includes("--check")) {
    const current = readFileSync(path, "utf8");
    if (current !== sql) {
      console.error(`RLS migration ${path} is out of date. Run: pnpm rls:generate`);
      process.exit(1);
    }
    console.info(`RLS migration is up to date (${TENANT_SCOPED_TABLES.length} tables).`);
    return;
  }

  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, sql);
  console.info(`Wrote ${path} (${TENANT_SCOPED_TABLES.length} tenant-scoped tables).`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main(process.argv.slice(2));
}
